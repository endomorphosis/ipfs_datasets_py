def seed(*, operator="+", name="amount", function="calculate", identity="seed"):
    type_ = "integer" if operator in ("+", "-", "*") else "boolean"
    source = f"def {function}({name}: int, threshold: int) -> {'int' if type_ == 'integer' else 'bool'}:\n"
    source += f"    return {name} {operator} threshold\n"
    refs = ("expr:" + name, "expr:threshold")
    return dict(id=identity, group_id="one-related-group", split="train", source_text=source,
        target=dict(kind="program_expression", document=ProgramExpression("expr:result", "binary", type_,
            operand_ids=refs, evaluation_order=refs, operator=operator, source_ref_ids=("source",)).to_dict()))


@pytest.mark.parametrize("operator", ["+", "-", "*", "<", "<=", ">", ">=", "==", "!="])
def test_all_operator_variants_preserve_targets_groups_and_parent_provenance(operator):
    parent = seed(operator=operator)
    before = deepcopy(parent)
    result = subject.augment_training_sources([parent])
    assert parent == before
    assert len(result["rows"]) == 12
    assert len({row["id"] for row in result["rows"]}) == 12
    assert len({row["source_text"] for row in result["rows"]}) == 12
    assert result["report"]["temporary_names_independent_of_style"] is True
    assert result["report"]["targets_changed"] is False
    assert result["report"]["validation_or_test_used"] is False
    assert result["report"]["proof_authority"] is False
    for row, binding in zip(result["rows"], result["report"]["bindings"]):
        assert set(row) == subject.FIELDS
        assert row["target"] == parent["target"] and row["target"] is not parent["target"]
        assert row["group_id"] == parent["group_id"] and row["split"] == "train"
        assert binding["id"] == row["id"] and binding["parent_id"] == parent["id"]
        assert binding["parent_source_sha256"] == hashlib.sha256(parent["source_text"].encode()).hexdigest()
        assert binding["source_sha256"] == hashlib.sha256(row["source_text"].encode()).hexdigest()


def test_temporary_identifiers_are_crossed_with_all_temporary_training_styles():
    result = subject.augment_training_sources([seed()])
    names = {}
    for row, binding in zip(result["rows"], result["report"]["bindings"]):
        if binding["style"] == 4:
            continue
        assignment = ast.parse(row["source_text"]).body[0].body[0]
        assert isinstance(assignment, ast.Assign)
        name = assignment.targets[0].id
        assert name == subject.TEMPORARY_NAMES[binding["nuisance_variant"]]
        names.setdefault(binding["style"], set()).add(name)
    assert set(names) == {5, 6, 7}
    assert all(values == set(subject.TEMPORARY_NAMES) for values in names.values())


def test_local_nuisance_cannot_shadow_an_operand_identifier():
    parent = seed(name="outcome")
    result = subject.augment_training_sources([parent], styles=(5,), nuisance_variants=(0,))
    tree = ast.parse(result["rows"][0]["source_text"])
    assert tree.body[0].body[0].targets[0].id == "outcome_local"
    assert result["rows"][0]["target"] == parent["target"]


@pytest.mark.parametrize("split", ["validation", "test", "canary", "tuning"])
def test_nontraining_seeds_are_rejected_before_rendering(monkeypatch, split):
    row = seed(); row["split"] = split
    monkeypatch.setattr(subject, "render_source_style", lambda *a, **k: pytest.fail("nontraining source rendered"))
    with pytest.raises(ValueError, match="train-only"):
        subject.augment_training_sources([row])


@pytest.mark.parametrize("extra", ["embedding", "proof_authority", "reference_metadata", "candidate_ir"])
def test_extra_seed_fields_cannot_enter_augmentation(extra):
    row = seed(); row[extra] = True
    with pytest.raises(ValueError, match="closed train-only"):
        subject.augment_training_sources([row])


def test_changed_target_or_rendered_operation_is_rejected_without_repair(monkeypatch):
    row = seed()
    row["target"]["document"]["operator"] = "-"
    before = deepcopy(row)
    with pytest.raises(ValueError, match="source/target mismatch"):
        subject.augment_training_sources([row])
    assert row == before
    render = subject.render_source_style
    monkeypatch.setattr(subject, "render_source_style", lambda *a, **k: render(*a, **k).replace(" + ", " - "))
    with pytest.raises(ValueError, match="did not preserve"):
        subject.augment_training_sources([seed()])


@pytest.mark.parametrize("options", [dict(styles=[]), dict(styles=[4, 4]), dict(styles=[8]), dict(styles=[True]),
    dict(styles=[[]]), dict(nuisance_variants=[]), dict(nuisance_variants=[0, 0]),
    dict(nuisance_variants=[False]), dict(nuisance_variants=[3]), dict(nuisance_variants=[{}])])
def test_unknown_duplicate_or_nontyped_augmentation_axes_are_rejected(options):
    with pytest.raises(ValueError, match="explicit unique"):
        subject.augment_training_sources([seed()], **options)


def test_duplicate_parent_sources_or_derived_identities_are_rejected():
    one, two = seed(), seed(identity="another")
    with pytest.raises(ValueError, match="duplicate training seed source"):
        subject.augment_training_sources([one, two])
    two = seed(identity="seed:style-4:nuisance-0", function="another")
    with pytest.raises(ValueError, match="identity collides"):
        subject.augment_training_sources([one, two])


