def fixture_module():
    path = Path(__file__).resolve().parents[5] / "tests/fixtures/logic/source_security_styles_v4.py"
    spec = importlib.util.spec_from_file_location("security_style_development_fixture", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_development_counts_group_lineage_and_label_vocab_without_opening_heldouts():
    fixture = fixture_module()
    base, validation, seeds = fixture.rows("train"), fixture.rows("validation"), fixture.rows("train", styles=(0,))
    assert len(base) == 336 and len(validation) == 504 and len(seeds) == 84
    closed_seeds = [{key: row[key] for key in subject.FIELDS} for row in seeds]
    augmented = subject.augment_training_sources(closed_seeds)
    combined = base + augmented["rows"]
    assert len(augmented["rows"]) == 1008 and len(combined) == 1344
    assert len({row["group_id"] for row in combined}) == 21
    assert len({row["group_id"] for row in validation}) == 7
    assert len({row["id"] for row in combined}) == len(combined)
    assert len({row["source_text"] for row in combined}) == len(combined)
    for key in ("id", "group_id", "source_text"):
        assert not {row[key] for row in combined} & {row[key] for row in validation}
    assert not {" ".join(row["source_text"].casefold().split()) for row in combined} & {
        " ".join(row["source_text"].casefold().split()) for row in validation}
    training_operators = {row["target"]["document"]["operator"] for row in combined}
    assert training_operators == {"+", "-", "*", "<", "<=", ">", ">=", "==", "!="}
    assert all(row["target"]["document"]["operator"] in training_operators for row in validation)
    for row in validation:
        assert subject.qualify_source_candidate(row["source_text"], row["target"])["status"] == "qualified"
    # Inspect only split assignments and manifest counts for future holdouts.
    groups = Counter(fixture.split_for(i, j) for i in range(len(fixture.NAMES)) for j in range(len(fixture.OPERATORS)))
    assert groups == {"train": 21, "validation": 7, "test": 7}
    manifest = fixture.manifest()
    assert manifest["combined_training_count"] == 1344 and manifest["validation_count"] == 504
    assert manifest["test_count"] == 504 and manifest["canary_count"] == 112
