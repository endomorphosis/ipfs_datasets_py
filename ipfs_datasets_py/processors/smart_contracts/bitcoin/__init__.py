"""Bitcoin smart-contract frontend package (CRYPTOIR-G250).

Bounded offline decoders and semantic records for Bitcoin **spend conditions**:
legacy Script, SegWit, Tapscript leaves/control blocks, descriptors, Miniscript,
witnesses, PSBT bindings, prevouts, sighash, timelock, hashlock, and threshold
paths.

Importing this package performs no network I/O, secret resolution, signing,
broadcast, or package installation.  Bitcoin is modeled as UTXO spend
conditions — not account contracts.
"""

