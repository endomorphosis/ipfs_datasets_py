def list_national_collectors(*, helpers: bool = False) -> tuple[NationalCollector, ...]:
    """Return vendored national collectors. Helpers are archive/Playwright utilities."""

    if helpers:
        return COLLECTORS
    return tuple(spec for spec in COLLECTORS if not spec.helper)


def get_national_collector(key: str) -> NationalCollector:
    """Look up a collector by ISO code, module stem, or filename."""

    text = str(key or "").strip().lower()
    if not text:
        raise KeyError("collector key is empty")
    if text.endswith(".py"):
        text = text[:-3]
    if text.startswith("collect_"):
        spec = BY_MODULE.get(text)
        if spec is not None:
            return spec
    if text in BY_ISO:
        return BY_ISO[text][0]
    spec = BY_MODULE.get(f"collect_{text}")
    if spec is not None:
        return spec
    raise KeyError(f"unknown national collector {key!r}")


def collector_for_hf_dataset(dataset_id: str) -> tuple[str, ...]:
    """Return collector module names (or in-tree module paths) for a Hub dataset id."""

    return BY_DATASET.get(str(dataset_id or "").strip().lower(), ())


def load_collector_module(key: str) -> Any:
    """Import one collector script with ``common`` on ``sys.path``.

    Does not run ``main()``. Scripts remain official-source research collectors.
    """

    spec = get_national_collector(key)
    path = str(COLLECTORS_DIR)
    if path not in sys.path:
        sys.path.insert(0, path)
    return import_module(spec.module)


def hf_dataset_coverage() -> dict[str, int]:
    """Count Hub datasets bound to vendored collectors or in-tree scrapers."""

    return {
        "vendored_collectors": len(list_national_collectors()),
        "helper_scripts": sum(1 for spec in COLLECTORS if spec.helper),
        "bound_hf_datasets": len(BY_DATASET),
        "in_tree_scraper_rows": len(IN_TREE_SCRAPERS),
    }


