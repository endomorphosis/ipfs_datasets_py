"""World ID Keccak/hash-to-field utilities and EIP-191 RP request signing.

Optional dependencies (pycryptodome Keccak and coincurve) are imported lazily
so that importing this module never fails solely because crypto extras are
missing; signing functions raise :class:`WorldIdSignatureError` instead.
"""

from __future__ import annotations

import secrets as random_secrets
import time
from dataclasses import dataclass
from typing import TYPE_CHECKING

from .config import DEFAULT_WORLD_ID_SIGNATURE_TTL_SECONDS, WorldIdConfig

if TYPE_CHECKING:
    pass

try:  # pragma: no cover - import failure is exercised by dependency health checks.
    from Crypto.Hash import keccak  # type: ignore[import-untyped]
except ImportError as exc:  # pragma: no cover
    keccak = None  # type: ignore[assignment]
    _KECCAK_IMPORT_ERROR: Exception | None = exc
else:
    _KECCAK_IMPORT_ERROR = None

try:  # pragma: no cover - import failure is exercised by dependency health checks.
    from coincurve import PrivateKey  # type: ignore[import-untyped]
except ImportError as exc:  # pragma: no cover
    PrivateKey = None  # type: ignore[assignment]
    _SIGNING_IMPORT_ERROR: Exception | None = exc
else:
    _SIGNING_IMPORT_ERROR = None


class WorldIdSignatureError(ValueError):
    """Raised when RP signature generation inputs are invalid."""


@dataclass(frozen=True)
class WorldIdRpSignature:
    """World ID RP signature payload generated by the backend."""

    signature: str
    nonce: str
    created_at: int
    expires_at: int
    action: str | None = None

    def to_protocol_dict(self) -> dict[str, object]:
        """Return the protocol field names used by World ID signing docs."""

        return {
            "sig": self.signature,
            "nonce": self.nonce,
            "created_at": self.created_at,
            "expires_at": self.expires_at,
        }

    def to_rp_context(self, rp_id: str) -> dict[str, object]:
        """Return an IDKit-ready RP context with the relying-party ID."""

        return {
            "rp_id": rp_id,
            **self.to_protocol_dict(),
        }


def world_id_keccak256(data: bytes) -> bytes:
    """Return Ethereum Keccak-256, not NIST SHA3-256."""

    _require_keccak_dependency()
    digest = keccak.new(digest_bits=256)
    digest.update(data)
    return digest.digest()


def hash_to_field(input_bytes: bytes | str) -> bytes:
    """Hash bytes to the World ID field element representation."""

    data = input_bytes.encode("utf-8") if isinstance(input_bytes, str) else bytes(input_bytes)
    value = int.from_bytes(world_id_keccak256(data), "big") >> 8
    return value.to_bytes(32, "big")


def hash_to_field_hex(input_bytes: bytes | str) -> str:
    """Return the ``0x``-prefixed hex encoding of :func:`hash_to_field`."""

    return "0x" + hash_to_field(input_bytes).hex()


def compute_rp_signature_message(
    nonce_bytes32: bytes | str,
    created_at: int,
    expires_at: int,
    action: str | None = None,
) -> bytes:
    """Build the exact bytes World ID requires before EIP-191 signing."""

    nonce = _parse_bytes32(nonce_bytes32, "nonce")
    created = _uint64(created_at, "created_at")
    expires = _uint64(expires_at, "expires_at")
    if expires <= created:
        raise WorldIdSignatureError("expires_at must be greater than created_at")
    message = b"\x01" + nonce + created.to_bytes(8, "big") + expires.to_bytes(8, "big")
    if action is not None:
        cleaned_action = str(action).strip()
        if not cleaned_action:
            raise WorldIdSignatureError("action must not be empty when provided")
        message += hash_to_field(cleaned_action)
    return message


def eip191_digest(message: bytes) -> bytes:
    """Apply the Ethereum Signed Message prefix and Keccak digest."""

    prefix = b"\x19Ethereum Signed Message:\n" + str(len(message)).encode("ascii")
    return world_id_keccak256(prefix + message)


def sign_world_id_request(
    signing_key_hex: str,
    *,
    action: str | None = None,
    ttl_seconds: int = DEFAULT_WORLD_ID_SIGNATURE_TTL_SECONDS,
    random_bytes: bytes | None = None,
    created_at: int | None = None,
) -> WorldIdRpSignature:
    """Generate a World ID RP signature from a backend signing key."""

    _require_signing_dependencies()
    key_bytes = _parse_private_key(signing_key_hex)
    ttl = int(ttl_seconds)
    if ttl <= 0:
        raise WorldIdSignatureError("ttl_seconds must be positive")
    created = int(time.time()) if created_at is None else _uint64(created_at, "created_at")
    expires = created + ttl
    if expires > (2**64 - 1):
        raise WorldIdSignatureError("expires_at exceeds uint64")
    entropy = random_secrets.token_bytes(32) if random_bytes is None else bytes(random_bytes)
    if len(entropy) != 32:
        raise WorldIdSignatureError("random_bytes must be exactly 32 bytes")
    nonce = hash_to_field(entropy)
    message = compute_rp_signature_message(nonce, created, expires, action)
    digest = eip191_digest(message)
    raw_signature = PrivateKey(key_bytes).sign_recoverable(digest, hasher=None)
    signature_bytes = raw_signature[:64] + bytes([int(raw_signature[64]) + 27])
    return WorldIdRpSignature(
        signature="0x" + signature_bytes.hex(),
        nonce="0x" + nonce.hex(),
        created_at=created,
        expires_at=expires,
        action=str(action).strip() if action is not None else None,
    )


def sign_world_id_request_from_config(
    config: WorldIdConfig,
    *,
    action: str | None = None,
    random_bytes: bytes | None = None,
    created_at: int | None = None,
) -> WorldIdRpSignature:
    """Generate an RP signature using a validated World ID config."""

    if not config.enabled:
        raise WorldIdSignatureError("World ID is disabled")
    selected_action = str(action or config.default_action).strip()
    if selected_action not in config.allowed_actions:
        raise WorldIdSignatureError("World ID action is not allowed")
    if not config.rp_signing_key.value:
        raise WorldIdSignatureError("WORLD_ID_RP_SIGNING_KEY value is required to sign requests")
    return sign_world_id_request(
        config.rp_signing_key.value,
        action=selected_action,
        ttl_seconds=config.rp_signature_ttl_seconds,
        random_bytes=random_bytes,
        created_at=created_at,
    )


def _require_signing_dependencies() -> None:
    if _SIGNING_IMPORT_ERROR is not None:
        raise WorldIdSignatureError("World ID signing dependencies are not installed") from _SIGNING_IMPORT_ERROR
    _require_keccak_dependency()


def _require_keccak_dependency() -> None:
    if _KECCAK_IMPORT_ERROR is not None:
        raise WorldIdSignatureError("World ID Keccak dependency is not installed") from _KECCAK_IMPORT_ERROR


def _parse_private_key(value: str) -> bytes:
    raw = str(value or "").strip()
    if raw.startswith("0x"):
        raw = raw[2:]
    try:
        key = bytes.fromhex(raw)
    except ValueError as exc:
        raise WorldIdSignatureError("signing key must be 32 bytes of hex") from exc
    if len(key) != 32:
        raise WorldIdSignatureError("signing key must be 32 bytes")
    return key


def _parse_bytes32(value: bytes | str, name: str) -> bytes:
    if isinstance(value, str):
        raw = value.strip()
        if raw.startswith("0x"):
            raw = raw[2:]
        try:
            data = bytes.fromhex(raw)
        except ValueError as exc:
            raise WorldIdSignatureError(f"{name} must be 32 bytes of hex") from exc
    else:
        data = bytes(value)
    if len(data) != 32:
        raise WorldIdSignatureError(f"{name} must be exactly 32 bytes")
    return data


def _uint64(value: int, name: str) -> int:
    parsed = int(value)
    if parsed < 0 or parsed > 2**64 - 1:
        raise WorldIdSignatureError(f"{name} must fit uint64")
    return parsed


