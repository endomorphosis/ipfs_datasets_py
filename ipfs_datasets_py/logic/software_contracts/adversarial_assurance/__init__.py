"""Public datasets exports for adversarial-assurance contracts (AAE-012).

Importing this package only exposes closed, versioned contract models and the
frozen ``AdversarialAssuranceArtifacts@1`` catalog. It does not open a store,
perform network I/O, start a campaign, or change production policy.

This package is the sole datasets freeze of adversarial-assurance exports and
canonical schemas. Signed receipts reuse the existing EdDSA/did:key receipt
signature authority and define no new envelope or cryptography.
"""

