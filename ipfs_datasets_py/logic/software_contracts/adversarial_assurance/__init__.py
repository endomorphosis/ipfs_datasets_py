def package_schema_paths() -> tuple[Path, ...]:
    """Return the frozen canonical schema files shipped with this package."""

    return (BASE_SCHEMA_PATH, RECEIPT_SCHEMA_PATH)


def freeze_adversarial_assurance_artifacts() -> AdversarialAssuranceArtifacts:
    """Return the sole frozen default package export catalog."""

    return AdversarialAssuranceArtifacts.freeze_default()


