"""Explicit administrative closeout with evidence-bound legacy external charges.

The old labels/amounts API did not enforce output paths. This opt-in therefore
requires every key to join two pinned original receipts and an independently
checked current named-root directory or absent leaf. Historical external file
contents and cumulative generated bytes are not reconstructed or authenticated.
No admission, deletion, native grant, cap migration or root migration occurs.
"""
from __future__ import annotations

import copy
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import time

from . import autoencoder_resource_recovery as base

resources = base.resources
DISPOSITION_SCHEMA = "conservative-named-roots-external-disposition/v1"
MAX_DISPOSITION_BYTES = 8 * 1024 * 1024
_SHA = re.compile(r"[0-9a-f]{64}\Z")


def _need(value, message):
    if not value:
        raise resources.DaemonResourceError(message)


def _wire(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()


def _directory_identity(path):
    path = resources._safe_path(path, directory=True)
    info = path.stat()
    return {"path": str(path), "device": info.st_dev, "inode": info.st_ino,
            "mode": info.st_mode, "uid": info.st_uid}


def _pointer(document, pointer):
    _need(type(pointer) is str and pointer.startswith("/") and len(pointer) <= 4096,
          "bounded explicit receipt JSON pointer required")
    current = document
    for raw in pointer[1:].split("/"):
        _need(re.search(r"~(?![01])", raw) is None, "invalid receipt pointer escape")
        token = raw.replace("~1", "/").replace("~0", "~")
        if type(current) is dict:
            _need(token in current, "receipt pointer is missing")
            current = current[token]
        elif type(current) is list:
            _need(token.isdecimal() and (token == "0" or not token.startswith("0"))
                  and int(token) < len(current), "receipt array pointer is missing")
            current = current[int(token)]
        else:
            raise resources.DaemonResourceError("receipt pointer crossed a scalar")
    return current


def _receipt(pin, attempt, attempt_inventory):
    _need(type(pin) is dict and set(pin) == {"path", "bytes", "sha256"}
          and type(pin["path"]) is str and type(pin["bytes"]) is int
          and 0 < pin["bytes"] <= MAX_DISPOSITION_BYTES
          and type(pin["sha256"]) is str and _SHA.fullmatch(pin["sha256"]),
          "bounded closed historical receipt pin required")
    path = resources._safe_path(pin["path"])
    _need(attempt in path.parents, "historical receipt must belong to the bound original attempt")
    row = {"path": str(path.relative_to(attempt)), "bytes": pin["bytes"], "sha256": pin["sha256"]}
    _need(row in attempt_inventory, "historical receipt is not in the exact durable attempt inventory")
    flags = os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC
    descriptor = os.open(path, flags)
    try:
        before = os.fstat(descriptor)
        _need(stat.S_ISREG(before.st_mode) and before.st_nlink == 1
              and before.st_size == pin["bytes"], "historical receipt identity differs")
        blocks, count = [], 0
        while True:
            block = os.read(descriptor, min(65536, pin["bytes"] + 1 - count))
            if not block:
                break
            count += len(block)
            _need(count <= pin["bytes"], "historical receipt grew")
            blocks.append(block)
        raw = b"".join(blocks)
        identity = lambda value: (value.st_dev, value.st_ino, value.st_size,
                                  value.st_mtime_ns, value.st_ctime_ns)
        _need(count == pin["bytes"] and hashlib.sha256(raw).hexdigest() == pin["sha256"]
              and identity(before) == identity(os.fstat(descriptor))
              and identity(before) == identity(path.stat()), "historical receipt changed")
    finally:
        os.close(descriptor)
    def pairs(items):
        value = {}
        for key, item in items:
            _need(key not in value, "duplicate historical receipt field")
            value[key] = item
        return value
    value = json.loads(raw, object_pairs_hook=pairs,
        parse_constant=lambda _: (_ for _ in ()).throw(resources.DaemonResourceError("nonfinite receipt")))
    _need(type(value) is dict, "historical receipt must be an object")
    return value


def _verify_disposition(disposition, charges, helper, attempt, attempt_inventory):
    _need(type(disposition) is dict and set(disposition) == {"schema", "external_charges_sha256", "bindings"}
          and disposition["schema"] == DISPOSITION_SCHEMA
          and disposition["external_charges_sha256"] == base._digest(charges),
          "exact explicit external-charge disposition required")
    bindings = disposition["bindings"]
    _need(type(bindings) is list and len(bindings) == len(charges), "every external charge needs one disposition")
    seen, observations = set(), []
    fields = {"key", "bytes", "charge_evidence_pin", "charge_json_pointer", "path_evidence_pin",
        "path_json_pointer", "outside_attempt_json_pointer", "association", "path", "disposition",
        "parent_identity", "directory_identity", "expected_artifacts"}
    for binding in bindings:
        _need(type(binding) is dict and set(binding) == fields, "closed external disposition entry required")
        key = binding["key"]
        _need(type(key) is str and key in charges and key not in seen
              and type(binding["bytes"]) is int and binding["bytes"] == charges[key],
              "external charge key or original amount differs")
        seen.add(key)
        declared = _receipt(binding["charge_evidence_pin"], attempt, attempt_inventory)
        path_receipt = _receipt(binding["path_evidence_pin"], attempt, attempt_inventory)
        charge = _pointer(declared, binding["charge_json_pointer"])
        _need(type(charge) is dict and charge.get("key") == key
              and type(charge.get("bytes")) is int and charge["bytes"] == charges[key],
              "historical receipt does not bind the original charge")
        association = binding["association"]
        _need(type(association) is dict and set(association) == {"mode", "charge_json_pointer", "path_json_pointer"},
              "closed historical receipt association required")
        if association["mode"] == "same_receipt":
            _need(binding["charge_evidence_pin"] == binding["path_evidence_pin"]
                  and association["charge_json_pointer"] is None and association["path_json_pointer"] is None
                  and binding["outside_attempt_json_pointer"] is None,
                  "same-document disposition must use one exact original receipt")
        elif association["mode"] == "same_declared_inputs":
            _need(_pointer(path_receipt, binding["outside_attempt_json_pointer"]) is True,
                  "historical external-path declaration is missing")
            _need(association["charge_json_pointer"] in {"/test_artifacts", "/b3_test_artifacts"}
                  and association["path_json_pointer"] in {"/test_artifacts", "/b3_test_artifacts"},
                  "only the reviewed declared test-source cohorts may associate receipts")
            left = _pointer(declared, association["charge_json_pointer"])
            right = _pointer(path_receipt, association["path_json_pointer"])
            _need(type(left) is list and bool(left) and _wire(left) == _wire(right),
                  "historical receipts do not share the exact declared input cohort")
            for pin in left:
                _need(type(pin) is dict and set(pin) == {"path", "bytes", "sha256"}
                      and type(pin["path"]) is str and Path(pin["path"]).is_absolute()
                      and type(pin["bytes"]) is int and pin["bytes"] > 0
                      and type(pin["sha256"]) is str and _SHA.fullmatch(pin["sha256"]),
                      "declared source cohort must contain historical file pins")
        else:
            _need(_pointer(path_receipt, binding["outside_attempt_json_pointer"]) is True,
                  "historical external-path declaration is missing")
            _need(association["mode"] == "direct_receipt_pin" and association["path_json_pointer"] is None
                  and _pointer(declared, association["charge_json_pointer"]) == binding["path_evidence_pin"],
                  "historical receipt does not bind the path receipt pin")
        spelling = binding["path"]
        _need(type(spelling) is str and Path(spelling).is_absolute()
              and ".." not in Path(spelling).parts, "absolute external path required")
        path = Path(spelling)
        _need(_pointer(path_receipt, binding["path_json_pointer"]) == spelling,
              "external path differs from the historical declaration")
        _need(any(root in path.parents for root in helper.roots)
              and path != attempt and attempt not in path.parents and path not in attempt.parents,
              "external path must be a separate strict named-root descendant")
        _need(_directory_identity(path.parent) == binding["parent_identity"], "external parent identity changed")
        artifacts = binding["expected_artifacts"]
        if binding["disposition"] == "absent_leaf":
            _need(binding["directory_identity"] is None and type(artifacts) is list and artifacts == [],
                  "absence cannot claim a historical file inventory")
            resources._safe_path(path, missing=True)
            _need(not path.exists() and not path.is_symlink(), "external leaf is no longer absent")
            current = []
        else:
            _need(binding["disposition"] == "retained_directory"
                  and _directory_identity(path) == binding["directory_identity"]
                  and type(artifacts) is list, "exact retained external directory required")
            current = base._durable_inventory(path)
            _need(current == artifacts, "current external directory inventory differs")
            _need(_directory_identity(path) == binding["directory_identity"], "external directory changed")
        _need(_directory_identity(path.parent) == binding["parent_identity"], "external parent changed during check")
        observations.append({"key": key, "last_known_charged_bytes": charges[key], "path": spelling,
            "disposition": binding["disposition"], "current_regular_file_count": len(current),
            "current_regular_file_bytes": sum(row["bytes"] for row in current),
            "historical_external_payloads_authenticated": False,
            "historical_receipt_association": association["mode"]})
    _need(seen == set(charges), "external charge disposition is incomplete")
    return observations


def reconcile_retained_reservations_batch(ledger_path, *, roots, claims, artifacts_durable=False):
    """Close an exact reviewed batch under one lock and two global censuses.

    This is administrative evidence preservation, with no native admission.
    Empty attempts retain the unchanged original failed-validation restriction.
    Every charge needs explicit current path disposition; an absent leaf never
    supplies a fabricated historical inventory. One later bad claim refuses
    the complete batch before the one atomic write. Final accounting is a
    prewrite projection; independently census the actual ledger after return.
    """
    _need(artifacts_durable is True, "explicit durable artifact assertion required")
    _need(type(roots) in (list, tuple) and len(roots) == 4, "original four named roots required")
    _need(type(claims) is list and 0 < len(claims) <= 128, "bounded exact batch claims required")
    try:
        frozen_raw = _wire(claims)
        _need(len(frozen_raw) <= 32 * 1024 * 1024, "batch disposition exceeds bound")
        frozen = json.loads(frozen_raw)
    except (TypeError, ValueError, RecursionError) as error:
        raise resources.DaemonResourceError("bounded explicit batch required") from error
    fields = {"reservation_id", "expected_record_sha256", "attempt_directory", "expected_artifacts",
              "allow_empty_failed_admission", "conservative_named_roots_external_disposition"}
    ids = set()
    for claim in frozen:
        _need(type(claim) is dict and set(claim) == fields
              and type(claim["reservation_id"]) is str and claim["reservation_id"]
              and claim["reservation_id"] not in ids
              and type(claim["expected_record_sha256"]) is str and _SHA.fullmatch(claim["expected_record_sha256"])
              and type(claim["expected_artifacts"]) is list
              and type(claim["allow_empty_failed_admission"]) is bool,
              "closed unique exact batch claim required")
        ids.add(claim["reservation_id"])
    helper = resources.DaemonResourceReservation(ledger_path, roots=roots,
        storage_bytes=1, memory_mb=1, ledger_lock_timeout_seconds=30, require_existing_ledger=True)
    with helper._locked():
        ledger = helper._read()
        others_sha = base._digest({k:v for k,v in ledger["reservations"].items() if k not in ids})
        selected = []
        for claim in frozen:
            record = ledger["reservations"].get(claim["reservation_id"])
            _need(record is not None and record["status"] == "retained"
                  and base._digest(record) == claim["expected_record_sha256"], "retained reservation identity changed")
            attempt = resources._safe_path(claim["attempt_directory"], directory=True)
            _need(any(root in attempt.parents for root in helper.roots)
                  and record.get("attempt_directory") == resources._root_identity(attempt),
                  "recovery attempt identity changed")
            charges = copy.deepcopy(resources._external_charges(record))
            empty = claim["allow_empty_failed_admission"]
            if empty:
                admission_fields = set("artifacts_durable_asserted attempt_directory child child_process_slots cpu_slots "
                    "created_at external_charges last_usage memory_mb owner_pid prior_children reservation_id "
                    "retention_reason scheduler_lane status storage_bytes workload".split())
                _need(set(record) == admission_fields and record["retention_reason"] == "scheduler_admission_failed"
                      and record["scheduler_lane"] == "validation" and record["workload"] == "canonical_validation"
                      and record["child"] is None and record["prior_children"] == []
                      and record["artifacts_durable_asserted"] is False and not charges
                      and claim["expected_artifacts"] == [], "unsupported empty failed admission")
            else:
                _need(bool(claim["expected_artifacts"]), "nonempty durable attempt inventory required")
            _need(bool(charges) == (claim["conservative_named_roots_external_disposition"] is not None),
                  "every external charge needs an explicit disposition; no-charge claims need none")
            selected.append((claim, record, attempt, charges))
        def unchanged():
            _need(_wire(claims) == frozen_raw, "batch request substituted")
            for claim, record, _, _ in selected:
                _need(ledger["reservations"].get(claim["reservation_id"]) is record
                      and base._digest(record) == claim["expected_record_sha256"],
                      "retained reservation changed during closeout")
            _need(base._digest({k:v for k,v in ledger["reservations"].items() if k not in ids}) == others_sha,
                  "another reservation changed")
        def verify_all():
            unchanged()
            values = []
            for claim, record, attempt, charges in selected:
                _need(resources._process(record["owner_pid"]) is None, "original reservation owner PID still exists")
                for child in [record.get("child"), *record.get("prior_children", ())]:
                    _need(not resources._group_usage(child)["live_processes"], "retained child group is still alive")
                _need(resources._root_identity(attempt) == record["attempt_directory"], "recovery attempt changed")
                if claim["allow_empty_failed_admission"]:
                    _need(not any(attempt.iterdir()), "empty failed admission attempt has entries")
                inventory = base._durable_inventory(attempt)
                _need(inventory == claim["expected_artifacts"], "durable recovery inventory differs")
                attempt_bytes = sum(row["bytes"] for row in inventory)
                _need(attempt_bytes <= record["storage_bytes"], "retained attempt exceeds original reservation")
                observations = (_verify_disposition(claim["conservative_named_roots_external_disposition"],
                    charges, helper, attempt, inventory) if charges else [])
                if claim["allow_empty_failed_admission"]:
                    _need(not any(attempt.iterdir()), "empty failed admission attempt changed")
                _need(resources._root_identity(attempt) == record["attempt_directory"], "recovery attempt changed")
                values.append((inventory, observations))
            unchanged()
            # Repeat process absence after all evidence callbacks, including a
            # later claim's durable receipt or directory reads.
            for _, record, _, _ in selected:
                _need(resources._process(record["owner_pid"]) is None, "original reservation owner PID still exists")
                for child in [record.get("child"), *record.get("prior_children", ())]:
                    _need(not resources._group_usage(child)["live_processes"], "retained child group is still alive")
            helper._verify_owner_roots()
            return values
        verified = verify_all()
        accounting = base._administrative_census(helper, ledger)
        _need(verify_all() == verified, "batch evidence changed during first census")
        projected = copy.deepcopy(ledger)
        for identity in ids:
            projected["reservations"][identity]["status"] = "released"
        projected_selected_sha = base._digest({k:projected["reservations"][k] for k in sorted(ids)})
        final = base._administrative_census(helper, projected)
        _need(verify_all() == verified, "batch evidence changed during projected census")
        promised = sum(record["storage_bytes"] for _,record,_,_ in selected)
        _need(accounting["outstanding_full_reservations_bytes"] - final["outstanding_full_reservations_bytes"] == promised
              and base._digest({k:projected["reservations"][k] for k in sorted(ids)}) == projected_selected_sha
              and base._digest({k:v for k,v in projected["reservations"].items() if k not in ids}) == others_sha,
              "projected batch accounting differs")
        released_at = time.time()
        _need(verify_all() == verified, "batch evidence changed before write")
        outcomes = []
        for (claim,record,_,charges),(inventory,observations) in zip(selected,verified):
            attempt_bytes = sum(row["bytes"] for row in inventory)
            external_bytes = sum(charges.values())
            outcome = {"reservation_id":claim["reservation_id"], "previous_record_sha256":claim["expected_record_sha256"],
                "artifacts":inventory, "preserved_external_charges":charges,
                "last_known_external_charged_bytes":external_bytes,
                "last_known_total_charged_bytes":attempt_bytes + external_bytes,
                "external_observations":observations, "allow_empty_failed_admission":claim["allow_empty_failed_admission"]}
            outcomes.append(outcome)
        receipt = {"schema":"explicit-retained-reservation-batch-reconciliation/v1",
            "capacity_policy":"administrative_closeout", "batch_request_sha256":hashlib.sha256(frozen_raw).hexdigest(),
            "claims":outcomes, "claim_count":len(outcomes), "released_promise_bytes":promised,
            "other_reservations_sha256":others_sha, "full_claim_accounting":accounting, "final_accounting":final,
            "historical_external_payloads_authenticated":False,
            "external_charge_labels_are_physical_byte_inventory":False,
            "original_four_named_roots_preserved":True,
            "final_accounting_is_prewrite_projection":True, "actual_postwrite_census_required":True,
            "fresh_global_inventory_count":2, "atomic_ledger_write_count":1,
            "new_reservation_created":False, "new_resource_lease_acquired":False, "cap_changed":False,
            "outputs_deleted":False, "automatic_expiry":False, "admitted":False}
        for (_,record,_,_),outcome in zip(selected,outcomes):
            record.update(status="released", artifacts_durable_asserted=True, released_at=released_at,
                final_accounting=final, final_attempt_bytes=sum(row["bytes"] for row in outcome["artifacts"]),
                final_external_charged_bytes=outcome["last_known_external_charged_bytes"],
                final_total_charged_bytes=outcome["last_known_total_charged_bytes"],
                attempt_exceeded_reservation=outcome["last_known_total_charged_bytes"] > record["storage_bytes"],
                explicit_reconciliation={"schema":receipt["schema"], "batch_request_sha256":receipt["batch_request_sha256"],
                    "claim_count":len(outcomes), "selected_claim":outcome, "other_reservations_sha256":others_sha,
                    "fresh_global_inventory_count":2, "final_accounting_is_prewrite_projection":True,
                    "actual_postwrite_census_required":True, "historical_external_payloads_authenticated":False,
                    "admitted":False, "cap_changed":False, "outputs_deleted":False})
        _need(base._digest({k:v for k,v in ledger["reservations"].items() if k not in ids}) == others_sha,
              "another reservation changed")
        helper._verify_owner_roots()
        helper._write(ledger)
        return receipt


def reconcile_retained_external_reservation(ledger_path, *, roots, reservation_id,
        expected_record_sha256, attempt_directory, expected_artifacts, artifacts_durable=False,
        conservative_named_roots_external_disposition=None):
    """One explicitly charged claim through the exact same atomic batch path."""
    _need(conservative_named_roots_external_disposition is not None, "explicit external disposition required")
    return reconcile_retained_reservations_batch(ledger_path, roots=roots, artifacts_durable=artifacts_durable,
        claims=[{"reservation_id":reservation_id,"expected_record_sha256":expected_record_sha256,
            "attempt_directory":str(attempt_directory),"expected_artifacts":expected_artifacts,
            "allow_empty_failed_admission":False,
            "conservative_named_roots_external_disposition":conservative_named_roots_external_disposition}])


__all__ = ["reconcile_retained_reservations_batch", "reconcile_retained_external_reservation"]
