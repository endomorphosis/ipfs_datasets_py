"""Explicit administrative closeout with evidence-bound legacy external charges.

The old labels/amounts API did not enforce output paths. This opt-in therefore
requires every key to join two pinned original receipts and an independently
checked current named-root directory or absent leaf. Historical external file
contents and cumulative generated bytes are not reconstructed or authenticated.
No admission, deletion, native grant, cap migration or root migration occurs.
"""
from __future__ import annotations

import copy
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import time

from . import autoencoder_resource_recovery as base

resources = base.resources
DISPOSITION_SCHEMA = "conservative-named-roots-external-disposition/v1"
MAX_DISPOSITION_BYTES = 8 * 1024 * 1024
_SHA = re.compile(r"[0-9a-f]{64}\Z")


def _need(value, message):
    if not value:
        raise resources.DaemonResourceError(message)


def _wire(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()


def _directory_identity(path):
    path = resources._safe_path(path, directory=True)
    info = path.stat()
    return {"path": str(path), "device": info.st_dev, "inode": info.st_ino,
            "mode": info.st_mode, "uid": info.st_uid}


def _pointer(document, pointer):
    _need(type(pointer) is str and pointer.startswith("/") and len(pointer) <= 4096,
          "bounded explicit receipt JSON pointer required")
    current = document
    for raw in pointer[1:].split("/"):
        _need(re.search(r"~(?![01])", raw) is None, "invalid receipt pointer escape")
        token = raw.replace("~1", "/").replace("~0", "~")
        if type(current) is dict:
            _need(token in current, "receipt pointer is missing")
            current = current[token]
        elif type(current) is list:
            _need(token.isdecimal() and (token == "0" or not token.startswith("0"))
                  and int(token) < len(current), "receipt array pointer is missing")
            current = current[int(token)]
        else:
            raise resources.DaemonResourceError("receipt pointer crossed a scalar")
    return current


def _receipt(pin, attempt, attempt_inventory):
    _need(type(pin) is dict and set(pin) == {"path", "bytes", "sha256"}
          and type(pin["path"]) is str and type(pin["bytes"]) is int
          and 0 < pin["bytes"] <= MAX_DISPOSITION_BYTES
          and type(pin["sha256"]) is str and _SHA.fullmatch(pin["sha256"]),
          "bounded closed historical receipt pin required")
    path = resources._safe_path(pin["path"])
    _need(attempt in path.parents, "historical receipt must belong to the bound original attempt")
    row = {"path": str(path.relative_to(attempt)), "bytes": pin["bytes"], "sha256": pin["sha256"]}
    _need(row in attempt_inventory, "historical receipt is not in the exact durable attempt inventory")
    flags = os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC
    descriptor = os.open(path, flags)
    try:
        before = os.fstat(descriptor)
        _need(stat.S_ISREG(before.st_mode) and before.st_nlink == 1
              and before.st_size == pin["bytes"], "historical receipt identity differs")
        blocks, count = [], 0
        while True:
            block = os.read(descriptor, min(65536, pin["bytes"] + 1 - count))
            if not block:
                break
            count += len(block)
            _need(count <= pin["bytes"], "historical receipt grew")
            blocks.append(block)
        raw = b"".join(blocks)
        identity = lambda value: (value.st_dev, value.st_ino, value.st_size,
                                  value.st_mtime_ns, value.st_ctime_ns)
        _need(count == pin["bytes"] and hashlib.sha256(raw).hexdigest() == pin["sha256"]
              and identity(before) == identity(os.fstat(descriptor))
              and identity(before) == identity(path.stat()), "historical receipt changed")
    finally:
        os.close(descriptor)
    def pairs(items):
        value = {}
        for key, item in items:
            _need(key not in value, "duplicate historical receipt field")
            value[key] = item
        return value
    value = json.loads(raw, object_pairs_hook=pairs,
        parse_constant=lambda _: (_ for _ in ()).throw(resources.DaemonResourceError("nonfinite receipt")))
    _need(type(value) is dict, "historical receipt must be an object")
    return value


def _verify_disposition(disposition, charges, helper, attempt, attempt_inventory):
    _need(type(disposition) is dict and set(disposition) == {"schema", "external_charges_sha256", "bindings"}
          and disposition["schema"] == DISPOSITION_SCHEMA
          and disposition["external_charges_sha256"] == base._digest(charges),
          "exact explicit external-charge disposition required")
    bindings = disposition["bindings"]
    _need(type(bindings) is list and len(bindings) == len(charges), "every external charge needs one disposition")
    seen, observations = set(), []
    fields = {"key", "bytes", "charge_evidence_pin", "charge_json_pointer", "path_evidence_pin",
        "path_json_pointer", "outside_attempt_json_pointer", "association", "path", "disposition",
        "parent_identity", "directory_identity", "expected_artifacts"}
    for binding in bindings:
        _need(type(binding) is dict and set(binding) == fields, "closed external disposition entry required")
        key = binding["key"]
        _need(type(key) is str and key in charges and key not in seen
              and type(binding["bytes"]) is int and binding["bytes"] == charges[key],
              "external charge key or original amount differs")
        seen.add(key)
        declared = _receipt(binding["charge_evidence_pin"], attempt, attempt_inventory)
        path_receipt = _receipt(binding["path_evidence_pin"], attempt, attempt_inventory)
        charge = _pointer(declared, binding["charge_json_pointer"])
        _need(type(charge) is dict and charge.get("key") == key
              and type(charge.get("bytes")) is int and charge["bytes"] == charges[key],
              "historical receipt does not bind the original charge")
        association = binding["association"]
        _need(type(association) is dict and set(association) == {"mode", "charge_json_pointer", "path_json_pointer"},
              "closed historical receipt association required")
        if association["mode"] == "same_receipt":
            _need(binding["charge_evidence_pin"] == binding["path_evidence_pin"]
                  and association["charge_json_pointer"] is None and association["path_json_pointer"] is None
                  and binding["outside_attempt_json_pointer"] is None,
                  "same-document disposition must use one exact original receipt")
        elif association["mode"] == "same_declared_inputs":
            _need(_pointer(path_receipt, binding["outside_attempt_json_pointer"]) is True,
                  "historical external-path declaration is missing")
            _need(association["charge_json_pointer"] in {"/test_artifacts", "/b3_test_artifacts"}
                  and association["path_json_pointer"] in {"/test_artifacts", "/b3_test_artifacts"},
                  "only the reviewed declared test-source cohorts may associate receipts")
            left = _pointer(declared, association["charge_json_pointer"])
            right = _pointer(path_receipt, association["path_json_pointer"])
            _need(type(left) is list and bool(left) and _wire(left) == _wire(right),
                  "historical receipts do not share the exact declared input cohort")
            for pin in left:
                _need(type(pin) is dict and set(pin) == {"path", "bytes", "sha256"}
                      and type(pin["path"]) is str and Path(pin["path"]).is_absolute()
                      and type(pin["bytes"]) is int and pin["bytes"] > 0
                      and type(pin["sha256"]) is str and _SHA.fullmatch(pin["sha256"]),
                      "declared source cohort must contain historical file pins")
        else:
            _need(_pointer(path_receipt, binding["outside_attempt_json_pointer"]) is True,
                  "historical external-path declaration is missing")
            _need(association["mode"] == "direct_receipt_pin" and association["path_json_pointer"] is None
                  and _pointer(declared, association["charge_json_pointer"]) == binding["path_evidence_pin"],
                  "historical receipt does not bind the path receipt pin")
        spelling = binding["path"]
        _need(type(spelling) is str and Path(spelling).is_absolute()
              and ".." not in Path(spelling).parts, "absolute external path required")
        path = Path(spelling)
        _need(_pointer(path_receipt, binding["path_json_pointer"]) == spelling,
              "external path differs from the historical declaration")
        _need(any(root in path.parents for root in helper.roots)
              and path != attempt and attempt not in path.parents and path not in attempt.parents,
              "external path must be a separate strict named-root descendant")
        _need(_directory_identity(path.parent) == binding["parent_identity"], "external parent identity changed")
        artifacts = binding["expected_artifacts"]
        if binding["disposition"] == "absent_leaf":
            _need(binding["directory_identity"] is None and type(artifacts) is list and artifacts == [],
                  "absence cannot claim a historical file inventory")
            resources._safe_path(path, missing=True)
            _need(not path.exists() and not path.is_symlink(), "external leaf is no longer absent")
            current = []
        else:
            _need(binding["disposition"] == "retained_directory"
                  and _directory_identity(path) == binding["directory_identity"]
                  and type(artifacts) is list, "exact retained external directory required")
            current = base._durable_inventory(path)
            _need(current == artifacts, "current external directory inventory differs")
            _need(_directory_identity(path) == binding["directory_identity"], "external directory changed")
        _need(_directory_identity(path.parent) == binding["parent_identity"], "external parent changed during check")
        observations.append({"key": key, "last_known_charged_bytes": charges[key], "path": spelling,
            "disposition": binding["disposition"], "current_regular_file_count": len(current),
            "current_regular_file_bytes": sum(row["bytes"] for row in current),
            "historical_external_payloads_authenticated": False,
            "historical_receipt_association": association["mode"]})
    _need(seen == set(charges), "external charge disposition is incomplete")
    return observations


# The opt-in failed-filesystem profile is separate from ordinary artifacts.
FAILED_FILESYSTEM_SCHEMA = "retained-failed-filesystem-manifest/v1"
MAX_FAILED_FILESYSTEM_ENTRIES = 32768
MAX_FAILED_FILESYSTEM_DEPTH = 64
MAX_FAILED_FILESYSTEM_MANIFEST_BYTES = 16 * 1024 * 1024


def _filesystem_stamp(info):
    return {"device": info.st_dev, "inode": info.st_ino, "mode": info.st_mode,
            "uid": info.st_uid, "links": info.st_nlink, "bytes": info.st_size,
            "mtime_ns": info.st_mtime_ns, "ctime_ns": info.st_ctime_ns}


def failed_filesystem_manifest(attempt_directory):
    """Observe/fsync a complete failed tree without opening special payloads.

    This returns a typed failure-disposition document, not an ordinary artifact
    inventory. Callers persist it outside the attempt and bind its exact pin.
    Symlink text is preserved verbatim; no target is resolved. FIFOs are only
    lstatted. Regular files are anchored with O_PATH before opening that held
    regular inode, so a pathname substitution cannot open a FIFO or device.
    """
    attempt = resources._safe_path(attempt_directory, directory=True)
    _need(hasattr(os, "O_PATH"), "anchored failed-filesystem inspection requires O_PATH")
    rows = []
    counts = {"directory": 0, "regular": 0, "symlink": 0, "fifo": 0}
    apparent = 0
    total_apparent = 0
    root_identity = resources._root_identity(attempt)
    root = os.open(attempt, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC)
    def same(left, right):
        _need(_filesystem_stamp(left) == _filesystem_stamp(right), "failed filesystem entry changed")
    def owned(info):
        _need(info.st_uid == os.getuid(), "foreign-owned failed filesystem entry")
        _need(stat.S_ISDIR(info.st_mode) or info.st_nlink == 1,
              "hardlinked failed filesystem payload is unsupported")
        _need(info.st_dev == root_identity["device"], "foreign-device failed filesystem entry")
    def walk(descriptor, relative, depth):
        nonlocal apparent, total_apparent
        _need(depth <= MAX_FAILED_FILESYSTEM_DEPTH, "failed filesystem depth bound exceeded")
        before = os.fstat(descriptor); owned(before)
        names = []
        with os.scandir(descriptor) as scan:
            for entry in scan:
                _need(len(rows) + len(names) < MAX_FAILED_FILESYSTEM_ENTRIES,
                      "failed filesystem entry bound exceeded")
                names.append(entry.name)
        for name in sorted(names):
            resources.native_deadlines._check_resource_operation_deadline()
            _need(name not in {".", ".."} and "/" not in name and "\x00" not in name,
                  "invalid failed filesystem entry name")
            _need(len(rows) < MAX_FAILED_FILESYSTEM_ENTRIES, "failed filesystem entry bound exceeded")
            path = str(Path(relative) / name)
            info = os.stat(name, dir_fd=descriptor, follow_symlinks=False); owned(info)
            item = {"path": path, "identity": _filesystem_stamp(info)}
            if not stat.S_ISDIR(info.st_mode):
                total_apparent += info.st_size
            if stat.S_ISDIR(info.st_mode):
                item["kind"] = "directory"
                child = os.open(name, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC,
                                dir_fd=descriptor)
                try:
                    same(info, os.fstat(child))
                    rows.append(item); counts["directory"] += 1
                    walk(child, path, depth + 1)
                    same(info, os.fstat(child))
                finally:
                    os.close(child)
            elif stat.S_ISREG(info.st_mode):
                item["kind"] = "regular"
                anchor = os.open(name, os.O_PATH | os.O_NOFOLLOW | os.O_CLOEXEC, dir_fd=descriptor)
                try:
                    same(info, os.fstat(anchor))
                    payload = os.open(f"/proc/self/fd/{anchor}", os.O_RDONLY | os.O_NONBLOCK | os.O_CLOEXEC)
                    try:
                        same(info, os.fstat(payload))
                        digest = hashlib.sha256(); total = 0
                        while True:
                            resources.native_deadlines._check_resource_operation_deadline()
                            block = os.read(payload, 1024 * 1024)
                            if not block:
                                break
                            total += len(block)
                            _need(total <= info.st_size, "failed filesystem payload grew")
                            digest.update(block)
                        _need(total == info.st_size, "failed filesystem payload shrank")
                        os.fsync(payload); same(info, os.fstat(payload))
                    finally:
                        os.close(payload)
                finally:
                    os.close(anchor)
                item.update(bytes=total, sha256=digest.hexdigest())
                apparent += total
                rows.append(item); counts["regular"] += 1
            elif stat.S_ISLNK(info.st_mode):
                target = os.readlink(name, dir_fd=descriptor)
                target_bytes = os.fsencode(target)
                _need(len(target_bytes) <= 4096, "failed symlink target text exceeds bound")
                item.update(kind="symlink", target=target,
                            target_sha256=hashlib.sha256(target_bytes).hexdigest())
                rows.append(item); counts["symlink"] += 1
            else:
                _need(stat.S_ISFIFO(info.st_mode), "unsupported failed filesystem special entry")
                item["kind"] = "fifo"
                rows.append(item); counts["fifo"] += 1
            same(info, os.stat(name, dir_fd=descriptor, follow_symlinks=False))
        os.fsync(descriptor)
        same(before, os.fstat(descriptor))
    try:
        initial = os.fstat(root)
        _need(stat.S_ISDIR(initial.st_mode)
              and (initial.st_dev, initial.st_ino) == (root_identity["device"], root_identity["inode"]),
              "failed filesystem root changed before traversal")
        walk(root, "", 0)
        _need(resources._root_identity(attempt) == root_identity
              and (os.fstat(root).st_dev, os.fstat(root).st_ino)
                  == (root_identity["device"], root_identity["inode"]), "failed filesystem root changed")
    finally:
        os.close(root)
    rows.sort(key=lambda item: item["path"])
    _need(bool(rows), "empty failed filesystem attempt is unsupported")
    result = {"schema": FAILED_FILESYSTEM_SCHEMA, "attempt_directory": root_identity,
              "entries": rows, "entry_count": len(rows), "typed_counts": counts,
              "regular_apparent_bytes": apparent, "apparent_bytes": total_apparent,
              "entries_sha256": base._digest(rows),
              "targets_followed": False, "special_payloads_opened": False,
              "ordinary_artifact_durability_asserted": False, "test_or_task_acceptance_asserted": False}
    _need(len(_wire(result)) <= MAX_FAILED_FILESYSTEM_MANIFEST_BYTES,
          "failed filesystem manifest byte bound exceeded")
    return result


def _failed_manifest_location(reference, attempt, roots):
    _need(type(reference) is dict and set(reference) == {"path", "bytes", "sha256"}
          and type(reference["bytes"]) is int and 0 < reference["bytes"] <= MAX_FAILED_FILESYSTEM_MANIFEST_BYTES
          and type(reference["sha256"]) is str and _SHA.fullmatch(reference["sha256"]),
          "exact bounded detached failed manifest pin required")
    spelling = reference["path"]
    _need(type(spelling) is str and Path(spelling).is_absolute() and len(spelling) <= 4096
          and ".." not in Path(spelling).parts and "\x00" not in spelling,
          "plain absolute failed manifest path required")
    path = resources._safe_path(spelling)
    _need(attempt not in path.parents and path != attempt and any(root in path.parents for root in roots),
          "failed manifest must be detached in the original named roots")
    return path


def _failed_manifest_bytes(reference, attempt, roots, parent_descriptor):
    path = _failed_manifest_location(reference, attempt, roots)
    anchor = os.open(path.name, os.O_PATH | os.O_NOFOLLOW | os.O_CLOEXEC, dir_fd=parent_descriptor)
    anchored = os.fstat(anchor)
    try:
        _need(stat.S_ISREG(anchored.st_mode) and anchored.st_nlink == 1 and anchored.st_uid == os.getuid(),
              "failed manifest must be a held unaliased ordinary file")
        descriptor = os.open(f"/proc/self/fd/{anchor}", os.O_RDONLY | os.O_NONBLOCK | os.O_CLOEXEC)
    finally:
        os.close(anchor)
    try:
        before = os.fstat(descriptor)
        _need(_filesystem_stamp(anchored) == _filesystem_stamp(before), "failed manifest anchor differs")
        _need(stat.S_ISREG(before.st_mode) and before.st_nlink == 1 and before.st_uid == os.getuid()
              and before.st_size == reference["bytes"], "failed manifest regular identity differs")
        chunks = []; count = 0
        while True:
            block = os.read(descriptor, min(65536, reference["bytes"] + 1 - count))
            if not block:
                break
            chunks.append(block); count += len(block)
            _need(count <= reference["bytes"], "failed manifest grew")
        raw = b"".join(chunks)
        _need(len(raw) == reference["bytes"] and hashlib.sha256(raw).hexdigest() == reference["sha256"],
              "failed manifest pin differs")
        os.fsync(descriptor)
        _need(_filesystem_stamp(before) == _filesystem_stamp(os.fstat(descriptor))
              == _filesystem_stamp(path.lstat()), "failed manifest changed")
    finally:
        os.close(descriptor)
    return raw, _filesystem_stamp(before)


def _failed_manifest(reference, attempt, roots):
    path = _failed_manifest_location(reference, attempt, roots)
    parent = resources._safe_path(path.parent, directory=True)
    parent_stamp = _filesystem_stamp(parent.lstat())
    directory = os.open(parent, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC)
    try:
        _need(parent_stamp == _filesystem_stamp(os.fstat(directory)) and parent_stamp["uid"] == os.getuid(),
              "detached failed manifest parent changed before file read")
        raw, manifest_identity = _failed_manifest_bytes(reference, attempt, roots, directory)
        def pairs(items):
            document = {}
            for key, value in items:
                _need(key not in document, "duplicate failed manifest field")
                document[key] = value
            return document
        try:
            document = json.loads(raw, object_pairs_hook=pairs,
                parse_constant=lambda _: (_ for _ in ()).throw(ValueError("nonfinite manifest")))
        except (TypeError, ValueError, RecursionError) as error:
            raise resources.DaemonResourceError("invalid failed manifest JSON") from error
        current = failed_filesystem_manifest(attempt)
        _need(type(document) is dict and _wire(document) == _wire(current),
              "complete typed failed filesystem manifest differs")
        repeated, repeated_identity = _failed_manifest_bytes(reference, attempt, roots, directory)
        _need(repeated == raw and repeated_identity == manifest_identity, "detached failed manifest changed during tree walk")
        _need(_filesystem_stamp(parent.lstat()) == parent_stamp == _filesystem_stamp(os.fstat(directory)),
              "detached failed manifest parent changed before fsync")
        os.fsync(directory)
        _need(_filesystem_stamp(parent.lstat()) == parent_stamp == _filesystem_stamp(os.fstat(directory)),
              "detached failed manifest parent changed during fsync")
        final_raw, final_identity = _failed_manifest_bytes(reference, attempt, roots, directory)
        _need(final_raw == raw and final_identity == manifest_identity,
              "detached failed manifest changed after directory fsync")
        _need(_filesystem_stamp(parent.lstat()) == parent_stamp == _filesystem_stamp(os.fstat(directory)),
              "detached failed manifest parent changed after file validation")
        return {"manifest": copy.deepcopy(reference), "schema": FAILED_FILESYSTEM_SCHEMA,
                "attempt_directory": current["attempt_directory"], "entry_count": current["entry_count"],
                "typed_counts": current["typed_counts"], "regular_apparent_bytes": current["regular_apparent_bytes"],
                "apparent_bytes": current["apparent_bytes"],
                "entries_sha256": current["entries_sha256"], "targets_followed": False,
                "special_payloads_opened": False, "ordinary_artifact_durability_asserted": False,
                "test_or_task_acceptance_asserted": False}
    finally:
        os.close(directory)


def _failed_native_absence(record, binding):
    from .existing_resource_scheduler import open_existing_scheduler
    _need(type(binding) is dict and set(binding) == {"state_path", "policy_sha256", "request_id"}
          and binding["state_path"] == record.get("scheduler_state_path")
          and type(binding["policy_sha256"]) is str and _SHA.fullmatch(binding["policy_sha256"])
          and type(binding["request_id"]) is str and 0 < len(binding["request_id"]) <= 256
          and type(record.get("native_lease_id")) is str and re.fullmatch(r"[0-9a-f]{32}", record["native_lease_id"])
          and type(record.get("scheduler_lane")) is str,
          "explicit current native broker policy and original lease binding required")
    # The caller pins the CURRENT broker policy. The historical disk record's
    # older policy is preserved verbatim and never presented as a release proof.
    scheduler = open_existing_scheduler(binding["state_path"], binding["policy_sha256"], inspection_only=True)
    observation = scheduler.inspect_lease(record["native_lease_id"],
        expected_request_id=binding["request_id"], expected_lane=record["scheduler_lane"],
        expected_owner_pid=record["owner_pid"], expected_owner_birth_marker=record.get("owner_birth"),
        bounded_lock_timeout=2)
    _need(observation["status"] == "absent" and observation["lease"] is None
          and observation["descendant_count"] == 0, "recorded native lease or descendants remain")
    return {"current_policy_sha256": binding["policy_sha256"], "lease_id": record["native_lease_id"],
            "request_id": binding["request_id"], "status": "absent", "descendant_count": 0,
            "historical_release_established": False}


def _reconcile_retained_reservations_batch(ledger_path, *, roots, claims, artifacts_durable=False,
        failed_filesystem_disposition=False):
    """Close an exact reviewed batch under one lock and two global censuses.

    This is administrative evidence preservation, with no native admission.
    Empty attempts retain the unchanged original failed-validation restriction.
    Every charge needs explicit current path disposition; an absent leaf never
    supplies a fabricated historical inventory. One later bad claim refuses
    the complete batch before the one atomic write. Final accounting is a
    prewrite projection; independently census the actual ledger after return.
    """
    if failed_filesystem_disposition:
        _need(failed_filesystem_disposition is True and artifacts_durable is False,
              "failed disposition cannot assert ordinary artifact durability")
    else:
        _need(artifacts_durable is True, "explicit durable artifact assertion required")
    _need(type(roots) in (list, tuple) and len(roots) == 4, "original four named roots required")
    _need(type(claims) is list and 0 < len(claims) <= 128, "bounded exact batch claims required")
    try:
        frozen_raw = _wire(claims)
        _need(len(frozen_raw) <= 32 * 1024 * 1024, "batch disposition exceeds bound")
        frozen = json.loads(frozen_raw)
    except (TypeError, ValueError, RecursionError) as error:
        raise resources.DaemonResourceError("bounded explicit batch required") from error
    fields = {"reservation_id", "expected_record_sha256", "attempt_directory", "expected_artifacts",
              "allow_empty_failed_admission", "conservative_named_roots_external_disposition"}
    if failed_filesystem_disposition:
        fields |= {"failed_filesystem_manifest", "native_inspection"}
    ids = set()
    for claim in frozen:
        _need(type(claim) is dict and set(claim) == fields
              and type(claim["reservation_id"]) is str and claim["reservation_id"]
              and claim["reservation_id"] not in ids
              and type(claim["expected_record_sha256"]) is str and _SHA.fullmatch(claim["expected_record_sha256"])
              and type(claim["expected_artifacts"]) is list
              and type(claim["allow_empty_failed_admission"]) is bool,
              "closed unique exact batch claim required")
        ids.add(claim["reservation_id"])
    helper = resources.DaemonResourceReservation(ledger_path, roots=roots,
        storage_bytes=1, memory_mb=1, ledger_lock_timeout_seconds=30, require_existing_ledger=True)
    with helper._locked():
        ledger = helper._read()
        others_sha = base._digest({k:v for k,v in ledger["reservations"].items() if k not in ids})
        selected = []
        for claim in frozen:
            record = ledger["reservations"].get(claim["reservation_id"])
            _need(record is not None and record["status"] == "retained"
                  and base._digest(record) == claim["expected_record_sha256"], "retained reservation identity changed")
            attempt = resources._safe_path(claim["attempt_directory"], directory=True)
            _need(any(root in attempt.parents for root in helper.roots)
                  and record.get("attempt_directory") == resources._root_identity(attempt),
                  "recovery attempt identity changed")
            charges = copy.deepcopy(resources._external_charges(record))
            empty = claim["allow_empty_failed_admission"]
            _need(not failed_filesystem_disposition or not empty,
                  "failed-filesystem profile cannot expand empty failed admission")
            if empty:
                admission_fields = set("artifacts_durable_asserted attempt_directory child child_process_slots cpu_slots "
                    "created_at external_charges last_usage memory_mb owner_pid prior_children reservation_id "
                    "retention_reason scheduler_lane status storage_bytes workload".split())
                _need(set(record) == admission_fields and record["retention_reason"] == "scheduler_admission_failed"
                      and record["scheduler_lane"] == "validation" and record["workload"] == "canonical_validation"
                      and record["child"] is None and record["prior_children"] == []
                      and record["artifacts_durable_asserted"] is False and not charges
                      and claim["expected_artifacts"] == [], "unsupported empty failed admission")
            elif failed_filesystem_disposition:
                _need(not charges and claim["expected_artifacts"] == []
                      and record.get("artifacts_durable_asserted") is False
                      and record.get("retention_reason") == "context_failed"
                      and record.get("workload") in {"canonical_validation", "canonical_parented_phase"},
                      "failed-filesystem profile requires a stopped failed attempt without external charges")
            else:
                _need(bool(claim["expected_artifacts"]), "nonempty durable attempt inventory required")
            _need(bool(charges) == (claim["conservative_named_roots_external_disposition"] is not None),
                  "every external charge needs an explicit disposition; no-charge claims need none")
            selected.append((claim, record, attempt, charges))
        if failed_filesystem_disposition:
            for claim, _, _, _ in selected:
                detached = Path(claim["failed_filesystem_manifest"]["path"])
                _need(not any(other == detached or other in detached.parents for _, _, other, _ in selected),
                      "failed manifest must be detached from every selected attempt")
        def unchanged():
            _need(_wire(claims) == frozen_raw, "batch request substituted")
            for claim, record, _, _ in selected:
                _need(ledger["reservations"].get(claim["reservation_id"]) is record
                      and base._digest(record) == claim["expected_record_sha256"],
                      "retained reservation changed during closeout")
            _need(base._digest({k:v for k,v in ledger["reservations"].items() if k not in ids}) == others_sha,
                  "another reservation changed")
        def verify_all():
            unchanged()
            values = []
            for claim, record, attempt, charges in selected:
                _need(resources._process(record["owner_pid"]) is None, "original reservation owner PID still exists")
                for child in [record.get("child"), *record.get("prior_children", ())]:
                    group = resources._group_usage(child)
                    _need(not group["live_processes"] and (not failed_filesystem_disposition or group.get("available") is True),
                          "retained child group is still alive or unobservable")
                _need(resources._root_identity(attempt) == record["attempt_directory"], "recovery attempt changed")
                if claim["allow_empty_failed_admission"]:
                    _need(not any(attempt.iterdir()), "empty failed admission attempt has entries")
                if failed_filesystem_disposition:
                    preserved = _failed_manifest(claim["failed_filesystem_manifest"], attempt, helper.roots)
                    native = _failed_native_absence(record, claim["native_inspection"])
                    inventory = []
                    attempt_bytes = preserved["apparent_bytes"]
                else:
                    inventory = base._durable_inventory(attempt)
                    _need(inventory == claim["expected_artifacts"], "durable recovery inventory differs")
                    attempt_bytes = sum(row["bytes"] for row in inventory)
                _need(attempt_bytes <= record["storage_bytes"], "retained attempt exceeds original reservation")
                observations = (_verify_disposition(claim["conservative_named_roots_external_disposition"],
                    charges, helper, attempt, inventory) if charges else [])
                if claim["allow_empty_failed_admission"]:
                    _need(not any(attempt.iterdir()), "empty failed admission attempt changed")
                _need(resources._root_identity(attempt) == record["attempt_directory"], "recovery attempt changed")
                if failed_filesystem_disposition:
                    observations = [{"failed_filesystem_disposition": preserved, "native_absence": native}]
                values.append((inventory, observations))
            unchanged()
            # Repeat process absence after all evidence callbacks, including a
            # later claim's durable receipt or directory reads.
            for _, record, _, _ in selected:
                _need(resources._process(record["owner_pid"]) is None, "original reservation owner PID still exists")
                for child in [record.get("child"), *record.get("prior_children", ())]:
                    group = resources._group_usage(child)
                    _need(not group["live_processes"] and (not failed_filesystem_disposition or group.get("available") is True),
                          "retained child group is still alive or unobservable")
            helper._verify_owner_roots()
            return values
        verified = verify_all()
        accounting = base._administrative_census(helper, ledger)
        _need(verify_all() == verified, "batch evidence changed during first census")
        projected = copy.deepcopy(ledger)
        for identity in ids:
            projected["reservations"][identity]["status"] = "released"
        projected_selected_sha = base._digest({k:projected["reservations"][k] for k in sorted(ids)})
        final = base._administrative_census(helper, projected)
        _need(verify_all() == verified, "batch evidence changed during projected census")
        promised = sum(record["storage_bytes"] for _,record,_,_ in selected)
        _need(accounting["outstanding_full_reservations_bytes"] - final["outstanding_full_reservations_bytes"] == promised
              and base._digest({k:projected["reservations"][k] for k in sorted(ids)}) == projected_selected_sha
              and base._digest({k:v for k,v in projected["reservations"].items() if k not in ids}) == others_sha,
              "projected batch accounting differs")
        released_at = time.time()
        _need(verify_all() == verified, "batch evidence changed before write")
        outcomes = []
        for (claim,record,_,charges),(inventory,observations) in zip(selected,verified):
            attempt_bytes = sum(row["bytes"] for row in inventory)
            external_bytes = sum(charges.values())
            outcome = {"reservation_id":claim["reservation_id"], "previous_record_sha256":claim["expected_record_sha256"],
                "artifacts":inventory, "preserved_external_charges":charges,
                "last_known_external_charged_bytes":external_bytes,
                "last_known_total_charged_bytes":attempt_bytes + external_bytes,
                "external_observations":observations, "allow_empty_failed_admission":claim["allow_empty_failed_admission"]}
            if failed_filesystem_disposition:
                # The complete typed rows remain in their durable detached file.
                # No special-entry or ordinary-artifact inventory is inlined.
                outcome.pop("artifacts")
                outcome.pop("external_observations")
                outcome.update(failed_filesystem_disposition=observations[0]["failed_filesystem_disposition"],
                    native_absence=observations[0]["native_absence"],
                    last_known_total_charged_bytes=observations[0]["failed_filesystem_disposition"]["apparent_bytes"],
                    ordinary_artifact_durability_asserted=False, test_or_task_acceptance_asserted=False)
            outcomes.append(outcome)
        receipt = {"schema":"explicit-retained-reservation-batch-reconciliation/v1",
            "capacity_policy":"administrative_closeout", "batch_request_sha256":hashlib.sha256(frozen_raw).hexdigest(),
            "claims":outcomes, "claim_count":len(outcomes), "released_promise_bytes":promised,
            "other_reservations_sha256":others_sha, "full_claim_accounting":accounting, "final_accounting":final,
            "historical_external_payloads_authenticated":False,
            "external_charge_labels_are_physical_byte_inventory":False,
            "original_four_named_roots_preserved":True,
            "final_accounting_is_prewrite_projection":True, "actual_postwrite_census_required":True,
            "fresh_global_inventory_count":2, "atomic_ledger_write_count":1,
            "new_reservation_created":False, "new_resource_lease_acquired":False, "cap_changed":False,
            "outputs_deleted":False, "automatic_expiry":False, "admitted":False}
        if failed_filesystem_disposition:
            receipt["schema"] = "retained-failed-filesystem-batch-disposition/v1"
            receipt["ordinary_artifact_durability_asserted"] = False
            receipt["test_or_task_acceptance_asserted"] = False
            receipt["complete_typed_manifests_detached"] = True
        for (_,record,_,_),outcome in zip(selected,outcomes):
            record.update(status="released", artifacts_durable_asserted=not failed_filesystem_disposition, released_at=released_at,
                final_accounting=final, final_attempt_bytes=(outcome["failed_filesystem_disposition"]["apparent_bytes"]
                    if failed_filesystem_disposition else sum(row["bytes"] for row in outcome["artifacts"])),
                final_external_charged_bytes=outcome["last_known_external_charged_bytes"],
                final_total_charged_bytes=outcome["last_known_total_charged_bytes"],
                attempt_exceeded_reservation=outcome["last_known_total_charged_bytes"] > record["storage_bytes"],
                explicit_reconciliation={"schema":receipt["schema"], "batch_request_sha256":receipt["batch_request_sha256"],
                    "claim_count":len(outcomes), "selected_claim":outcome, "other_reservations_sha256":others_sha,
                    "fresh_global_inventory_count":2, "final_accounting_is_prewrite_projection":True,
                    "actual_postwrite_census_required":True, "historical_external_payloads_authenticated":False,
                    "admitted":False, "cap_changed":False, "outputs_deleted":False})
        _need(base._digest({k:v for k,v in ledger["reservations"].items() if k not in ids}) == others_sha,
              "another reservation changed")
        helper._verify_owner_roots()
        if not failed_filesystem_disposition:
            helper._write(ledger)
            return receipt
        expected_written_sha = base._digest(ledger)
        ledger_write_attempted = False
        ledger_write_returned = False
        try:
            ledger_write_attempted = True
            helper._write(ledger)
            ledger_write_returned = True
            _need(base._digest(helper._read()) == expected_written_sha,
                  "failed-filesystem ledger readback differs")
        except BaseException as error:
            observation = {"automatic_replay_permitted": False,
                "ledger_write_attempted": ledger_write_attempted, "ledger_write_returned": ledger_write_returned,
                "write_completed": True if ledger_write_returned else None,
                "observed_write_disposition": "unknown", "rollback_asserted": False, "expected_written_ledger_sha256": expected_written_sha,
                "observed_ledger_sha256": None, "observed_selected_record_sha256": None,
                "error_type": type(error).__name__, "receipt": receipt}
            try:
                observed = helper._read()
                observation["observed_ledger_sha256"] = base._digest(observed)
                observation["observed_selected_record_sha256"] = {
                    key: base._digest(observed["reservations"].get(key)) for key in sorted(ids)}
                if observation["observed_ledger_sha256"] == expected_written_sha:
                    observation["observed_write_disposition"] = "exact_expected_postimage"
                elif (all(observation["observed_selected_record_sha256"][claim["reservation_id"]]
                          == claim["expected_record_sha256"] for claim, _, _, _ in selected)
                      and base._digest({k:v for k,v in observed["reservations"].items() if k not in ids}) == others_sha):
                    observation["observed_write_disposition"] = "exact_selected_preimages"
                else:
                    observation["observed_write_disposition"] = "different_current_state"
            except BaseException as readback_error:
                observation["readback_error_type"] = type(readback_error).__name__
            raise FailedFilesystemDispositionWriteIncomplete(observation) from error
        receipt["actual_ledger_write_readback_verified"] = True
        return receipt



class FailedFilesystemDispositionWriteIncomplete(resources.DaemonResourceError):
    """A write/readback failed; inspect current state before any further action."""
    def __init__(self, observation):
        self.observation = observation
        super().__init__("failed-filesystem disposition write/readback incomplete; automatic replay forbidden")


def reconcile_retained_reservations_batch(ledger_path, *, roots, claims, artifacts_durable=False):
    """Unchanged strict ordinary/external-artifact administrative batch API."""
    return _reconcile_retained_reservations_batch(ledger_path, roots=roots, claims=claims,
                                                artifacts_durable=artifacts_durable)


def reconcile_retained_failed_filesystem_reservations_batch(ledger_path, *, roots, claims,
        failed_filesystem_disposition=False):
    """Opt in to stopped FAILED artifact disposition, never task/test acceptance.

    Each original six-field batch claim additionally supplies an exact detached
    ``failed_filesystem_manifest`` pin and current-policy ``native_inspection``.
    Ordinary expected_artifacts must be empty, external charges/empty-parented
    expansion are forbidden, and the original durability flag stays false.
    A subsequent actual original-owner census is required before closeout.
    """
    _need(failed_filesystem_disposition is True, "explicit failed-filesystem disposition required")
    return _reconcile_retained_reservations_batch(ledger_path, roots=roots, claims=claims,
        artifacts_durable=False, failed_filesystem_disposition=True)

def reconcile_retained_external_reservation(ledger_path, *, roots, reservation_id,
        expected_record_sha256, attempt_directory, expected_artifacts, artifacts_durable=False,
        conservative_named_roots_external_disposition=None):
    """One explicitly charged claim through the exact same atomic batch path."""
    _need(conservative_named_roots_external_disposition is not None, "explicit external disposition required")
    return reconcile_retained_reservations_batch(ledger_path, roots=roots, artifacts_durable=artifacts_durable,
        claims=[{"reservation_id":reservation_id,"expected_record_sha256":expected_record_sha256,
            "attempt_directory":str(attempt_directory),"expected_artifacts":expected_artifacts,
            "allow_empty_failed_admission":False,
            "conservative_named_roots_external_disposition":conservative_named_roots_external_disposition}])


