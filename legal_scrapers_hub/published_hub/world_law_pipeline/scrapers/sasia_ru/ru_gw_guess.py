"""RU gap work (2026-10-31): discover Gosweb municipal sites by guessing hostnames <stem>-r<RR>.gosweb.gosuslugi.ru from
the Wikidata RU municipality labels (_ru/wd_ru.jsonl), then scrape found hosts with ru_gosweb.scrape_host and stage.
Live only, direct connection (no proxy/VPN), robots.txt per host via rfc9309 (a host "exists" iff its robots.txt is 200).
Name-verified against the site title (ru_gosweb.name_ok); hosts generated by >1 place are skipped as ambiguous.
Resumable: _ru/gw_guess_done.txt (qids), results _ru/gw_guess_found.jsonl. Stops staging if /workspace free < 10 GB.
Usage: ru_gw_guess.py [--limit N] [--per-place K] [--stage]"""
import os as _wl_os  # WORLD_LAW_ROOT / GLOBAL_MUNICIPALITIES_ROOT override the default paths
import sys, os, re, json, time, shutil, argparse, resource
from datetime import datetime, timezone
for k in ('http_proxy','https_proxy','HTTP_PROXY','HTTPS_PROXY','ALL_PROXY','all_proxy'): os.environ.pop(k, None)
os.environ['ARCHIVE_LANE'] = 'sasia_ru'
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ru_gosweb as G
resource.setrlimit(resource.RLIMIT_AS, (1_500_000_000, 1_500_000_000))  # hard cap; RSS target < 500 MB
D = (_wl_os.environ.get("WORLD_LAW_ROOT", "/workspace/world_law") + '/staging/sasia_ru/_ru')
PROBE_DELAY = 1.0
TR = dict(zip("абвгдеёжзийклмнопрстуфхцчшщъыьэюя", ["a","b","v","g","d","e","yo","zh","z","i","j","k","l","m","n","o","p","r","s","t","u","f","x","c","ch","sh","shh","","y","","e","yu","ya"]))
GENERIC = set("поселение сельское сельсовет городское муниципальное образование село округ город городской посёлок поселок наслег области деревня район рабочий поселения муниципальный сельского волость поссовет национальный сумон станица хутор аул городского типа зато сельский территория межселенная внутригородское внутригородской".split())
# OKTMO 2-digit prefix -> subject (licence-plate) code; gosweb uses either in -rNN
SUBJ = {'01':'22','03':'23','04':'24','05':'25','07':'26','08':'27','10':'28','11':'29','12':'30','14':'31','15':'32','17':'33','18':'34','19':'35','20':'36','22':'52','24':'37','25':'38','26':'06','27':'39','28':'69','29':'40','30':'41','32':'42','33':'43','34':'44','35':'91','36':'63','37':'45','38':'46','40':'78','41':'47','42':'48','44':'49','45':'77','46':'50','47':'51','49':'53','50':'54','52':'55','53':'56','54':'57','56':'58','57':'59','58':'60','60':'61','61':'62','63':'64','64':'65','65':'66','66':'67','67':'92','68':'68','69':'70','70':'71','71':'72','73':'73','75':'74','76':'75','77':'87','78':'76','79':'01','80':'02','81':'03','82':'05','83':'07','84':'04','85':'08','86':'10','87':'11','88':'12','89':'13','90':'15','91':'09','92':'16','93':'17','94':'18','95':'19','96':'20','97':'21','98':'14','99':'79'}
def tl(s): return "".join(TR.get(c, c) for c in s)
def stems(label):
    s = re.sub(r"\([^)]*\)", " ", (label or "").lower()).replace("ё", "ё")
    toks = [t for t in re.findall(r"[а-яё]+(?:-[а-яё]+)*", s) if t not in GENERIC and len(t) > 1]
    if not toks: return []
    out = []
    j = "".join(tl(t).replace("-", "") for t in toks); out.append(j)
    if len(toks) > 1: out += ["-".join(tl(t) for t in toks), tl(toks[0]).replace("-", "")]
    if "-" in toks[0]: out.append(tl(toks[0]))
    b = re.sub(r"(skij|skoe|skaya)$", "sk", tl(toks[0]).replace("-", ""))
    if b.endswith("sk") and b != j: out.append(b)
    if "сельсовет" in s: out.append(tl(toks[0]).replace("-", "") + "selsovet")
    out += [x.replace("yo", "e") for x in out if "yo" in x]
    return [x for x in dict.fromkeys(out) if re.fullmatch(r"[a-z0-9-]{3,60}", x)][:5]
def name_latin(label):
    s = re.sub(r"\([^)]*\)", " ", (label or "").lower())
    toks = [t for t in re.findall(r"[а-яё]+(?:-[а-яё]+)*", s) if t not in GENERIC and len(t) > 1]
    return " ".join(G.translit(t) for t in toks)
def regions(oktmo):
    p = {o[:2] for o in oktmo or [] if len(o) >= 2}; r = []
    for x in p: r += [x, SUBJ.get(x)]
    return [x for x in dict.fromkeys(r) if x]
def free_gb(): return shutil.disk_usage('/workspace').free / 1e9
def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--limit', type=int, default=0); ap.add_argument('--per-place', type=int, default=10)
    ap.add_argument('--stage', action='store_true'); ap.add_argument('--qids', default=''); a = ap.parse_args()
    L = [json.loads(l) for l in open(f'{D}/wd_ru.jsonl')]
    seen_q = set()
    for f in ('gosweb_hosts_verified.jsonl', 'gosweb_hosts_verified2.jsonl', 'gosweb_hosts_engalychevo.jsonl'):
        for l in open(f'{D}/{f}'): seen_q.add(json.loads(l)['place_id'][3:])
    donef = f'{D}/gw_guess_done.txt'; done = set(open(donef).read().split()) if os.path.exists(donef) else set()
    cand = {}  # host -> set(qid)
    plan = []
    for x in L:
        hs = [f"{st}-r{rr}.gosweb.gosuslugi.ru" for st in stems(x.get('ru')) for rr in regions(x.get('oktmo'))]
        for h in hs: cand.setdefault(h, set()).add(x['qid'])
        plan.append((x, hs))
    if a.qids: want = set(a.qids.split(',')); plan = [p for p in plan if p[0]['qid'] in want]
    now = datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'); n = 0
    fo = open(f'{D}/gw_guess_found.jsonl', 'a'); fd = open(donef, 'a')
    print(json.dumps({'start': now, 'places': len(plan), 'skip_known': len(seen_q), 'done': len(done)}), flush=True)
    for x, hs in plan:
        q = x['qid']
        if q in done or q in seen_q or not hs: continue
        if a.limit and n >= a.limit: break
        n += 1; res = {'qid': q, 'ru': x.get('ru'), 'tried': len(hs)}
        for h in hs:
            if len(cand[h]) > 1: res.setdefault('ambig', []).append(h); continue
            time.sleep(PROBE_DELAY)
            try: rr = G.S.get(f'https://{h}/robots.txt', timeout=(10, 30), allow_redirects=False); sc = rr.status_code
            except Exception as e: sc = type(e).__name__
            if sc != 200 and not G.RESPECT_ROBOTS and isinstance(sc, int):  # robots.txt is only a host-exists probe; fall back to homepage
                try: sc = G.S.get(f'https://{h}/', timeout=(10, 30), allow_redirects=False).status_code
                except Exception as e: sc = type(e).__name__
            if sc != 200: continue
            res['host'] = h
            try: recs, st = G.scrape_host(h, 'wd:' + q, name_latin(x.get('ru')), a.per_place, now, verify_name=True)
            except Exception as e: recs, st = [], f'error {type(e).__name__}'
            res['status'] = st; res['docs'] = len(recs)
            if st.startswith('name_mismatch'): res.pop('host'); res.setdefault('mismatch', []).append(h); continue
            if a.stage and recs:
                while free_gb() < 10: print(json.dumps({'disk_low_gb': round(free_gb(), 1), 'sleep': 3600}), flush=True); time.sleep(3600)
                res['staged'] = G.stage(recs, 'RU', 'wd:' + q)
            break
        fo.write(json.dumps(res, ensure_ascii=False) + '\n'); fo.flush()
        fd.write(q + '\n'); fd.flush()
        if res.get('host'): print(json.dumps(res, ensure_ascii=False), flush=True)
    print(json.dumps({'end': datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'), 'processed': n}), flush=True)
if __name__ == '__main__': main()
