#!/usr/bin/env python3
"""Install a recurring public USPTO portfolio refresh schedule.

Generates systemd user timer/service units and an optional cron fragment that
run ``portfolio_cli.py refresh`` (public ODP only — never Patent Center login,
sign, pay, or push).

Hard policy:

* Templates are written under the portfolio state root.
* systemd/cron are **not** enabled unless ``--activate`` is passed.
* Runs source ``~/.config/ipfs_datasets_py/uspto.env`` for ``USPTO_ODP_API_KEY``.
* Serializes with a flock so overlapping ticks are skipped.

CLI::

    install_portfolio_schedule.py install [--interval-hours 24]
    install_portfolio_schedule.py activate
    install_portfolio_schedule.py status
    install_portfolio_schedule.py uninstall
    install_portfolio_schedule.py tick [--dry-run]
"""

from __future__ import annotations

import argparse
import fcntl
import json
import os
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Sequence

SCHEMA = "patlaw-portfolio-schedule-v1"
UNIT_NAME = "patlaw-portfolio-refresh"
DEFAULT_INTERVAL_HOURS = 24


def utc_now() -> str:
    return (
        datetime.now(timezone.utc)
        .replace(microsecond=0)
        .isoformat()
        .replace("+00:00", "Z")
    )


def default_state_root() -> Path:
    xdg = os.environ.get("XDG_STATE_HOME")
    base = Path(xdg) if xdg else Path.home() / ".local" / "state"
    return base / "ipfs_datasets_py" / "patent_portfolio" / "operator-default"


def default_repo_root() -> Path:
    # scripts/ops/uspto/thisfile.py → repo root is parents[3]
    return Path(__file__).resolve().parents[3]


def schedule_dir(state_root: Path) -> Path:
    return state_root / "schedule"


def write_templates(
    *,
    state_root: Path,
    repo_root: Path,
    interval_hours: int,
    python: str,
) -> dict[str, Path]:
    sched = schedule_dir(state_root)
    sched.mkdir(parents=True, exist_ok=True)
    runs = sched / "runs"
    runs.mkdir(parents=True, exist_ok=True)
    templates = sched / "templates"
    templates.mkdir(parents=True, exist_ok=True)

    env_file = Path.home() / ".config" / "ipfs_datasets_py" / "uspto.env"
    cli = repo_root / "scripts" / "ops" / "uspto" / "portfolio_cli.py"
    runner = sched / "run_refresh.sh"
    lock = sched / "refresh.lock"
    log = runs / "last_refresh.log"

    runner_body = f"""#!/usr/bin/env bash
# Generated by install_portfolio_schedule.py — public ODP portfolio refresh only.
set -euo pipefail
STATE_ROOT={state_root!s}
REPO_ROOT={repo_root!s}
ENV_FILE={env_file!s}
CLI={cli!s}
PYTHON={python!s}
LOCK={lock!s}
LOG={log!s}
mkdir -p "$(dirname "$LOG")"
exec 9>"$LOCK"
if ! flock -n 9; then
  echo "$(date -u +%Y-%m-%dT%H:%M:%SZ) skip: refresh already running" | tee -a "$LOG"
  exit 0
fi
{{
  echo "$(date -u +%Y-%m-%dT%H:%M:%SZ) start portfolio refresh"
  if [[ -f "$ENV_FILE" ]]; then
    # shellcheck disable=SC1090
    source "$ENV_FILE"
  fi
  if [[ -z "${{USPTO_ODP_API_KEY:-}}" ]]; then
    echo "USPTO_ODP_API_KEY missing; aborting" >&2
    exit 2
  fi
  export PYTHONPATH="$REPO_ROOT${{PYTHONPATH:+:$PYTHONPATH}}"
  "$PYTHON" "$CLI" --state-root "$STATE_ROOT" refresh
  echo "$(date -u +%Y-%m-%dT%H:%M:%SZ) done"
}} >>"$LOG" 2>&1
"""
    runner.write_text(runner_body)
    os.chmod(runner, 0o700)

    service = f"""[Unit]
Description=PATLAW public USPTO portfolio ODP refresh
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
ExecStart={runner}
Nice=10
# Never inherits secrets from the unit file; loads uspto.env inside the runner.

[Install]
WantedBy=default.target
"""
    timer = f"""[Unit]
Description=PATLAW public USPTO portfolio ODP refresh timer

[Timer]
OnBootSec=15min
OnUnitActiveSec={int(interval_hours)}h
AccuracySec=5min
Persistent=true
Unit={UNIT_NAME}.service

[Install]
WantedBy=timers.target
"""
    cron = (
        f"# PATLAW portfolio public refresh every {interval_hours}h "
        f"(opt-in; do not install without review)\\n"
        f"0 */{max(1, int(interval_hours))} * * * {runner} # patlaw-portfolio-refresh\\n"
    )

    service_path = templates / f"{UNIT_NAME}.service"
    timer_path = templates / f"{UNIT_NAME}.timer"
    cron_path = templates / "crontab.fragment"
    service_path.write_text(service)
    timer_path.write_text(timer)
    cron_path.write_text(cron.replace("\\n", "\n"))

    manifest = {
        "schema": SCHEMA,
        "installed_at_utc": utc_now(),
        "state_root": str(state_root),
        "repo_root": str(repo_root),
        "interval_hours": int(interval_hours),
        "unit_name": UNIT_NAME,
        "runner": str(runner),
        "templates": {
            "service": str(service_path),
            "timer": str(timer_path),
            "cron": str(cron_path),
        },
        "capabilities": {
            "public_odp_refresh": True,
            "patent_center_login": False,
            "sign_pay_file": False,
            "git_push": False,
        },
        "activated": False,
    }
    manifest_path = sched / "install_manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    return {
        "runner": runner,
        "service": service_path,
        "timer": timer_path,
        "cron": cron_path,
        "manifest": manifest_path,
    }


def activate(state_root: Path) -> dict[str, Any]:
    sched = schedule_dir(state_root)
    templates = sched / "templates"
    service_src = templates / f"{UNIT_NAME}.service"
    timer_src = templates / f"{UNIT_NAME}.timer"
    if not service_src.is_file() or not timer_src.is_file():
        raise SystemExit("templates missing; run install first")

    user_dir = Path.home() / ".config" / "systemd" / "user"
    user_dir.mkdir(parents=True, exist_ok=True)
    service_dst = user_dir / f"{UNIT_NAME}.service"
    timer_dst = user_dir / f"{UNIT_NAME}.timer"
    shutil.copy2(service_src, service_dst)
    shutil.copy2(timer_src, timer_dst)

    steps: list[str] = []
    for cmd in (
        ["systemctl", "--user", "daemon-reload"],
        ["systemctl", "--user", "enable", "--now", f"{UNIT_NAME}.timer"],
    ):
        proc = subprocess.run(cmd, capture_output=True, text=True)
        steps.append(
            {
                "cmd": cmd,
                "returncode": proc.returncode,
                "stdout": (proc.stdout or "")[-500:],
                "stderr": (proc.stderr or "")[-500:],
            }
        )
        if proc.returncode != 0:
            raise SystemExit(
                f"activation failed: {' '.join(cmd)}: {proc.stderr or proc.stdout}"
            )

    marker = sched / "ACTIVATED"
    marker.write_text(utc_now() + "\n")
    manifest_path = sched / "install_manifest.json"
    if manifest_path.is_file():
        manifest = json.loads(manifest_path.read_text())
        manifest["activated"] = True
        manifest["activated_at_utc"] = utc_now()
        manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    return {"ok": True, "steps": steps, "service": str(service_dst), "timer": str(timer_dst)}


def uninstall(state_root: Path) -> dict[str, Any]:
    results: dict[str, Any] = {"stopped": [], "removed": []}
    for cmd in (
        ["systemctl", "--user", "disable", "--now", f"{UNIT_NAME}.timer"],
        ["systemctl", "--user", "disable", "--now", f"{UNIT_NAME}.service"],
    ):
        proc = subprocess.run(cmd, capture_output=True, text=True)
        results["stopped"].append(
            {"cmd": cmd, "returncode": proc.returncode, "stderr": (proc.stderr or "")[-300:]}
        )
    user_dir = Path.home() / ".config" / "systemd" / "user"
    for name in (f"{UNIT_NAME}.service", f"{UNIT_NAME}.timer"):
        path = user_dir / name
        if path.is_file():
            path.unlink()
            results["removed"].append(str(path))
    subprocess.run(["systemctl", "--user", "daemon-reload"], capture_output=True)
    marker = schedule_dir(state_root) / "ACTIVATED"
    if marker.is_file():
        marker.unlink()
    return results


def status(state_root: Path) -> dict[str, Any]:
    sched = schedule_dir(state_root)
    manifest_path = sched / "install_manifest.json"
    out: dict[str, Any] = {
        "schema": SCHEMA,
        "state_root": str(state_root),
        "manifest_exists": manifest_path.is_file(),
        "activated_marker": (sched / "ACTIVATED").is_file(),
    }
    if manifest_path.is_file():
        out["manifest"] = json.loads(manifest_path.read_text())
    for cmd_key, cmd in (
        ("timer", ["systemctl", "--user", "is-active", f"{UNIT_NAME}.timer"]),
        ("timer_enabled", ["systemctl", "--user", "is-enabled", f"{UNIT_NAME}.timer"]),
        ("list_timers", ["systemctl", "--user", "list-timers", f"{UNIT_NAME}.timer", "--no-pager"]),
    ):
        proc = subprocess.run(cmd, capture_output=True, text=True)
        out[cmd_key] = {
            "returncode": proc.returncode,
            "stdout": (proc.stdout or "").strip(),
            "stderr": (proc.stderr or "").strip(),
        }
    log = sched / "runs" / "last_refresh.log"
    if log.is_file():
        text = log.read_text(errors="replace")
        out["last_log_tail"] = text[-1500:]
    return out


def tick(state_root: Path, *, dry_run: bool = False) -> dict[str, Any]:
    runner = schedule_dir(state_root) / "run_refresh.sh"
    if not runner.is_file():
        raise SystemExit("runner missing; run install first")
    if dry_run:
        return {"ok": True, "dry_run": True, "runner": str(runner)}
    proc = subprocess.run([str(runner)], capture_output=True, text=True)
    return {
        "ok": proc.returncode == 0,
        "returncode": proc.returncode,
        "stdout_tail": (proc.stdout or "")[-1000:],
        "stderr_tail": (proc.stderr or "")[-1000:],
    }


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        "--state-root",
        default="",
        help="Portfolio state root (default XDG patent_portfolio/operator-default)",
    )
    p.add_argument(
        "--repo-root",
        default="",
        help="ipfs_datasets_py checkout used by the timer (default: this repo)",
    )
    sub = p.add_subparsers(dest="command", required=True)

    inst = sub.add_parser("install", help="Write runner + systemd/cron templates")
    inst.add_argument("--interval-hours", type=int, default=DEFAULT_INTERVAL_HOURS)
    inst.add_argument("--python", default=sys.executable)
    inst.add_argument(
        "--repo-root",
        default="",
        help="Override repo root for this install (also accepted before subcommand)",
    )
    inst.add_argument(
        "--activate",
        action="store_true",
        help="Also enable the systemd user timer after install",
    )

    sub.add_parser("activate", help="Enable systemd user timer from templates")
    sub.add_parser("uninstall", help="Disable timer and remove user units")
    sub.add_parser("status", help="Show install/activation/timer status")
    t = sub.add_parser("tick", help="Run one refresh now via the installed runner")
    t.add_argument("--dry-run", action="store_true")
    return p


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    state = (
        Path(args.state_root).expanduser().resolve()
        if args.state_root
        else default_state_root()
    )
    repo_arg = getattr(args, "repo_root", "") or ""
    repo = (
        Path(repo_arg).expanduser().resolve()
        if str(repo_arg).strip()
        else default_repo_root()
    )

    if args.command == "install":
        paths = write_templates(
            state_root=state,
            repo_root=repo,
            interval_hours=int(args.interval_hours),
            python=str(args.python),
        )
        payload: dict[str, Any] = {
            "ok": True,
            "action": "install",
            "paths": {k: str(v) for k, v in paths.items()},
        }
        if args.activate:
            payload["activation"] = activate(state)
        print(json.dumps(payload, indent=2))
        return 0
    if args.command == "activate":
        print(json.dumps(activate(state), indent=2, default=str))
        return 0
    if args.command == "uninstall":
        print(json.dumps(uninstall(state), indent=2))
        return 0
    if args.command == "status":
        print(json.dumps(status(state), indent=2))
        return 0
    if args.command == "tick":
        print(json.dumps(tick(state, dry_run=bool(args.dry_run)), indent=2))
        return 0
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
